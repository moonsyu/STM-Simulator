import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PART_LIBRARY} from '../../../../src/part-library.js';
import {family} from '../../../../scripts/docs-audit/runtime.mjs';
import paths from '../../../../scripts/docs-audit/paths.cjs';

// Only the packaged-observation checks from docs-audit/verify.mjs are applied.
// No bare-metal, migration, public-asset, or physical-board claim is made here.
const {out,version}=paths,partial=process.argv.includes('--partial'),problems=[],missing=[],rows=[];
const read=async name=>{try{return JSON.parse(await fs.readFile(new URL(name,out),'utf8'));}catch(error){if(error.code==='ENOENT'){missing.push(name);return null;}throw error;}};
const packaged=await read('packaged-summary.json');
if(packaged){
 if(packaged.version!==version)problems.push('packaged-summary version mismatch');
 const expected=PART_LIBRARY.map(p=>p.type).sort(),actual=packaged.rows.map(p=>p.type).sort();
 if(JSON.stringify(actual)!==JSON.stringify(expected))problems.push('packaged-summary missing or duplicate device types');
}
for(const {type,name}of PART_LIBRARY){
 const app=await read(`packaged-${type}.json`),generated=await read(type+'.stm32lab'),saved=await read(`packaged-${type}.stm32lab`);
 if(!app||!generated||!saved)continue;
 const applied=app.events?.find(e=>e.type==='docs.applied'),states=app.events?.filter(e=>e.type==='simulation.state')||[];
 const text=(app.console||[]).map(e=>e.message).join('\n'),inputChecks=[];
 if(/ds18b20/.test(type))inputChecks.push(/10\.00/.test(text)&&/45\.00/.test(text));
 if(['encoder','ref_encoder_module_5'].includes(type))inputChecks.push(/count=3 edges=12/.test(text)&&/count=1 edges=4/.test(text));
 if(family(type)==='sd')inputChecks.push(/SD OCR=40ff8000/.test(text));
 if(family(type)==='tft'){
  const expected=createHash('sha256').update(JSON.stringify(Array.from({length:128*160},(_,i)=>i%128<43?0xf800:i%128<86?0x07e0:0x001f))).digest('hex');
  inputChecks.push(states.some(e=>e.detail.parts.selected?.device?.ram?.sha256===expected));
 }
 const checks={version:app.version===version,applied:app.applied===true,started:app.started===true,correctTarget:applied?.detail.binding.type===type,sameCode:saved.code===generated.code,sameWires:JSON.stringify(saved.wires)===JSON.stringify(generated.wires),stateEvents:states.length>0,simulationTime:app.simulationMs>=(/dht|ds18b20/.test(type)?5500:3500),noError:!app.error&&!app.errors?.length,inputChecks:inputChecks.every(Boolean),noFault:!states.some(e=>e.detail.fault)};
 const failures=Object.entries(checks).filter(([,passed])=>!passed).map(([key])=>key);
 if(failures.length)problems.push(type+': '+failures.join(', '));
 rows.push({type,name,passed:failures.length===0,checks,stateEvents:states.length,simulationMs:app.simulationMs,stimuli:app.stimuli,inputChecks,error:app.error,errors:app.errors});
}
const complete=missing.length===0&&rows.length===PART_LIBRARY.length;
const report={version,checkedAt:new Date().toISOString(),stage:!packaged?'pending-packaged-summary':packaged.dev?'development-electron':'packaged-app-observation',complete,passed:complete&&problems.length===0,expectedDevices:PART_LIBRARY.length,observedDevices:rows.length,passedDevices:rows.filter(r=>r.passed).length,problems,missing,testedExecutable:packaged?.exe,testedExecutableSha256:packaged?.exeSha256,scope:'Docs UI apply/start and diagnostic logs; expected code/wires are generated by the source audit. Separate core/cards verification establishes behavior and API exercise.',excluded:['bare-metal runtime','migration fixtures','diagnostic-size focused checks','public EXE asset/hash verification','physical STM32 execution'],rows};
await fs.writeFile(new URL('packaged-observation-summary.json',out),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({...report,rows:undefined},null,2));
if(!partial&&!report.passed)process.exitCode=1;
