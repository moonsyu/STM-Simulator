// Interrupt handlers of the enabled NVIC lines, as CubeMX writes them into stm32xxxx_it.c. The generated main.c shows the
// ones the built-in interpreter runs (UART/USART, timers, EXTI, DMA, DCMI, SDIO); the GCC build adds every missing one to
// its environment file, so a project without them (or an older main.c) still links with working interrupts.
import {isSerial,serialHandle} from './serial-config.js';
import {isTimer} from './timer-config.js';

export const dmaHandle=request=>request==='MEMTOMEM'?'hdma_memtomem':'hdma_'+request.toLowerCase();
const usartHandle=id=>'husart'+id.replace(/\D/g,'');

// [{name, irq, body, extern, shown}] — `body` is empty for a line with nothing to serve (a peripheral that is off),
// `shown` marks handlers the generated main.c carries.
export function irqHandlers(mcu){
  const peripherals=mcu?.peripherals||{},pins=mcu?.pins||{},out=[],streams=new Set();
  const sync=id=>peripherals[id]?.mode==='synchronous';
  // DMA stream interrupts generated by MX_DMA_Init need HAL_DMA_IRQHandler on the linked handle.
  for(const [request,d]of Object.entries(mcu?.dma||{})){if(!d?.stream||streams.has(d.stream))continue;streams.add(d.stream);const h=dmaHandle(request);
    out.push({name:`${d.stream}_IRQHandler`,irq:`${d.stream}_IRQn`,body:`HAL_DMA_IRQHandler(&${h});`,extern:`extern DMA_HandleTypeDef ${h};`,shown:true});}
  // Each enabled interrupt calls the HAL handler of its own peripheral; EXTI lines only serve the pins they route.
  const extiPins=(lo,hi)=>Object.entries(pins).filter(([pin,q])=>q.function==='GPIO_EXTI'&&Number(pin.slice(2))>=lo&&Number(pin.slice(2))<=hi).map(([pin])=>`HAL_GPIO_EXTI_IRQHandler(GPIO_PIN_${pin.slice(2)});`).join('');
  const of=(type,id,name,call,shown)=>peripherals[id]?.enabled?{extern:`extern ${type}_HandleTypeDef ${name};`,body:`${call}(&${name});`,shown}:{body:''};
  const body=id=>{
    // A timer/UART interrupt left on for a disabled peripheral has no handle to serve.
    if((isTimer(id)||isSerial(id))&&!peripherals[id]?.enabled)return {body:''};
    if(isTimer(id))return {body:`HAL_TIM_IRQHandler(&htim${id.slice(3)});`,extern:`extern TIM_HandleTypeDef htim${id.slice(3)};`,shown:true};
    if(isSerial(id))return sync(id)?{body:`HAL_USART_IRQHandler(&${usartHandle(id)});`,extern:`extern USART_HandleTypeDef ${usartHandle(id)};`,shown:true}:{body:`HAL_UART_IRQHandler(&${serialHandle(id)});`,extern:`extern UART_HandleTypeDef ${serialHandle(id)};`,shown:true};
    const exti=/^EXTI(\d+)(?:_(\d+))?$/.exec(id);if(exti){const a=Number(exti[1]),b=exti[2]===undefined?a:Number(exti[2]);return {body:extiPins(Math.min(a,b),Math.max(a,b)),shown:true};}
    if(id==='I2C1_EV')return of('I2C','I2C1','hi2c1','HAL_I2C_EV_IRQHandler',false);
    if(id==='I2C1_ER')return of('I2C','I2C1','hi2c1','HAL_I2C_ER_IRQHandler',false);
    if(id==='SPI1')return of('SPI','SPI1','hspi1','HAL_SPI_IRQHandler',false);
    if(id==='ADC'||id==='ADC1_2')return of('ADC','ADC1','hadc1','HAL_ADC_IRQHandler',false);
    if(id==='DCMI')return of('DCMI','DCMI','hdcmi','HAL_DCMI_IRQHandler',true);
    if(id==='SDIO')return of('SD','SDIO','hsd','HAL_SD_IRQHandler',true);
    return {body:''};
  };
  for(const [irq,p]of Object.entries(mcu?.nvic||{}))if(p.enabled&&!streams.has(irq.replace('_IRQn',''))){const id=irq.replace('_IRQn','');out.push({name:`${id}_IRQHandler`,irq,shown:false,...body(id)});}
  return out;
}

// CubeMX-style handler text for main.c, with its two user sections.
export const handlerText=h=>[`void ${h.name}(void) {`,`  /* USER CODE BEGIN ${h.irq} 0 */`,`  /* USER CODE END ${h.irq} 0 */`,...h.body.split(/(?<=;)/).map(s=>'  '+s),`  /* USER CODE BEGIN ${h.irq} 1 */`,`  /* USER CODE END ${h.irq} 1 */`,'}'];
